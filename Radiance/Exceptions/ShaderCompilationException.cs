namespace Radiance.Exceptions;

/// <summary>
/// Represents a error that occurs when a shader compilation fails.
/// </summary>
public class ShaderCompilationException(string stage, string log, string source) : RadianceException
{
    public string Stage => stage;
    public string Log => log;
    public string ShaderSource => source;

    public override string ErrorMessage =>
        $"""
        The {stage} shader generated by Radiance failed to compile.
        Driver log:
        {log}
        Generated source:
        {source}
        """;

    public override string Message => ErrorMessage;
}
