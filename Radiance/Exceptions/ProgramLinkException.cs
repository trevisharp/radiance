namespace Radiance.Exceptions;

/// <summary>
/// Represents a error that occurs when a program linking fails.
/// </summary>
public class ProgramLinkException(string log, string vertexSource, string fragmentSource) : RadianceException
{
    public string Log => log;

    public override string ErrorMessage =>
        $"""
        The shaders generated by Radiance failed to link.
        Driver log:
        {log}
        Vertex shader:
        {vertexSource}
        Fragment shader:
        {fragmentSource}
        """;

    public override string Message => ErrorMessage;
}
